// CRC32 Lookup Table
function makeCrcTable(): Uint32Array {
  const table = new Uint32Array(256);
  for (let i = 0; i < 256; i++) {
    let c = i;
    for (let k = 0; k < 8; k++) {
      c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    }
    table[i] = c >>> 0;
  }
  return table;
}
const crcTable = makeCrcTable();

function calculateCrc32(data: Uint8Array): number {
  let crc = 0xffffffff;
  for (let i = 0; i < data.length; i++) {
    crc = (crc >>> 8) ^ crcTable[(crc ^ data[i]) & 0xff];
  }
  return (crc ^ 0xffffffff) >>> 0;
}

interface ZipFileEntry {
  path: string;
  data: Uint8Array;
}

function createZipArchive(files: ZipFileEntry[]): Uint8Array {
  const localHeaders: Uint8Array[] = [];
  const centralHeaders: Uint8Array[] = [];
  let currentOffset = 0;

  files.forEach((file) => {
    const pathBytes = new TextEncoder().encode(file.path);
    const crc = calculateCrc32(file.data);
    const size = file.data.length;

    // Local Header
    const lh = new Uint8Array(30 + pathBytes.length + size);
    const lView = new DataView(lh.buffer);
    lView.setUint32(0, 0x04034b50, true); // signature
    lView.setUint16(4, 20, true); // version needed (2.0)
    lView.setUint16(6, 0, true); // flags
    lView.setUint16(8, 0, true); // compression: 0 (STORED)
    lView.setUint16(10, 0, true); // mod time
    lView.setUint16(12, 0, true); // mod date
    lView.setUint32(14, crc, true); // crc32
    lView.setUint32(18, size, true); // compressed size
    lView.setUint32(22, size, true); // uncompressed size
    lView.setUint16(26, pathBytes.length, true);
    lView.setUint16(28, 0, true); // extra length
    lh.set(pathBytes, 30);
    lh.set(file.data, 30 + pathBytes.length);
    localHeaders.push(lh);

    // Central Directory Header
    const ch = new Uint8Array(46 + pathBytes.length);
    const cView = new DataView(ch.buffer);
    cView.setUint32(0, 0x02014b50, true); // signature
    cView.setUint16(4, 20, true); // version made by
    cView.setUint16(6, 20, true); // version needed
    cView.setUint16(8, 0, true);
    cView.setUint16(10, 0, true);
    cView.setUint16(12, 0, true);
    cView.setUint16(14, 0, true);
    cView.setUint32(16, crc, true);
    cView.setUint32(20, size, true);
    cView.setUint32(24, size, true);
    cView.setUint16(28, pathBytes.length, true);
    cView.setUint16(30, 0, true);
    cView.setUint16(32, 0, true);
    cView.setUint16(34, 0, true);
    cView.setUint16(36, 0, true);
    cView.setUint32(38, 0, true);
    cView.setUint32(42, currentOffset, true); // relative offset of local header
    ch.set(pathBytes, 46);
    centralHeaders.push(ch);

    currentOffset += lh.length;
  });

  const cdSize = centralHeaders.reduce((acc, h) => acc + h.length, 0);

  // End of Central Directory
  const eocd = new Uint8Array(22);
  const eView = new DataView(eocd.buffer);
  eView.setUint32(0, 0x06054b50, true);
  eView.setUint16(4, 0, true); // disk number
  eView.setUint16(6, 0, true); // disk with central directory
  eView.setUint16(8, files.length, true); // entries on disk
  eView.setUint16(10, files.length, true); // total entries
  eView.setUint32(12, cdSize, true); // size of CD
  eView.setUint32(16, currentOffset, true); // offset of CD
  eView.setUint16(20, 0, true); // comment length

  // Assemble full zip
  const totalLength = currentOffset + cdSize + 22;
  const result = new Uint8Array(totalLength);
  let pos = 0;
  localHeaders.forEach((lh) => {
    result.set(lh, pos);
    pos += lh.length;
  });
  centralHeaders.forEach((ch) => {
    result.set(ch, pos);
    pos += ch.length;
  });
  result.set(eocd, pos);

  return result;
}

