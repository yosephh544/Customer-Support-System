// -------------------------------------------------------------
// Helper: Text Sanitizer for Standard Type 1 ASCII PDF Fonts
// -------------------------------------------------------------

function sanitizePdfText(text: string | number | undefined | null): string {
  if (text === undefined || text === null) return '';
  const str = String(text);
  return str
    .replace(/\\/g, '\\\\')
    .replace(/\(/g, '\\(')
    .replace(/\)/g, '\\)')
    .replace(/[^\x20-\x7E]/g, (char) => {
      if (char === '•') return '*';
      if (char === '—' || char === '–') return '-';
      if (char === '★' || char === '☆') return '*';
      if (char === '“' || char === '”') return '"';
      if (char === '‘' || char === '’') return "'";
      return ' ';
    });
}

function escapeXml(str: string | number | undefined | null): string {
  if (str === undefined || str === null) return '';
  return String(str)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&apos;');
}

