// Native PDF 1.4 Generator
// -------------------------------------------------------------

export function exportToPdf(options: PdfReportOptions): void {
  const {
    fileName,
    title,
    subtitle = 'Customer Support Operational Dossier',
    authorOrRole = 'Customer Support System',
    date = new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'short', day: 'numeric' }),
    kpis = [],
    sections = [],
    notes = [],
  } = options;

  const pageWidth = 612; // Standard Letter (points)
  const pageHeight = 792;
  const margin = 40;
  const contentWidth = pageWidth - margin * 2;

  // We will collect commands per page
  const pages: string[] = [];
  let currentCommands: string[] = [];
  let curY = pageHeight - margin;

  const startNewPage = () => {
    if (currentCommands.length > 0) {
      pages.push(currentCommands.join('\n'));
      currentCommands = [];
    }
    curY = pageHeight - margin;

    // Header top accent line
    currentCommands.push(
      'q',
      '0.09 0.38 0.82 rg', // Primary Blue
      `${margin} ${pageHeight - 20} ${contentWidth} 4 re`,
      'f',
      'Q'
    );
  };

  startNewPage();

  // Document Title Banner on Page 1
  currentCommands.push(
    'q',
    '0.06 0.13 0.24 rg', // Navy
    `${margin} ${curY - 32} ${contentWidth} 32 re`,
    'f',
    'Q',
    'BT',
    '/F2 16 Tf',
    '1 1 1 rg', // White
    `1 0 0 1 ${margin + 12} ${curY - 22} Tm`,
    `(${sanitizePdfText(title)}) Tj`,
    'ET'
  );
  curY -= 42;

  // Subtitle & Meta Bar
  currentCommands.push(
    'BT',
    '/F1 9 Tf',
    '0.4 0.45 0.52 rg',
    `1 0 0 1 ${margin} ${curY} Tm`,
    `(${sanitizePdfText(subtitle)}  |  Generated by: ${sanitizePdfText(authorOrRole)}  |  Date: ${sanitizePdfText(date)}) Tj`,
    'ET'
  );
  curY -= 18;

  // Horizontal divider
  currentCommands.push(
    'q',
    '0.85 0.88 0.92 RG',
    '1 w',
    `${margin} ${curY} m ${margin + contentWidth} ${curY} l S`,
    'Q'
  );
  curY -= 15;

  // KPI Scorecards (if provided)
  if (kpis.length > 0) {
    const kpiCount = Math.min(kpis.length, 5);
    const cardGap = 8;
    const cardWidth = (contentWidth - cardGap * (kpiCount - 1)) / kpiCount;
    const cardHeight = 44;

    kpis.slice(0, 5).forEach((kpi, idx) => {
      const cardX = margin + idx * (cardWidth + cardGap);
      const cardY = curY - cardHeight;

      // Card Background
      currentCommands.push(
        'q',
        '0.96 0.97 0.99 rg', // Light slate
        `${cardX} ${cardY} ${cardWidth} ${cardHeight} re`,
        'f',
        '0.85 0.88 0.92 RG',
        '0.75 w',
        `${cardX} ${cardY} ${cardWidth} ${cardHeight} re`,
        'S',
        'Q'
      );

      // KPI Value
      currentCommands.push(
        'BT',
        '/F2 14 Tf',
        kpi.color === 'success'
          ? '0.09 0.63 0.32 rg'
          : kpi.color === 'danger'
          ? '0.86 0.15 0.15 rg'
          : kpi.color === 'warning'
          ? '0.85 0.47 0.03 rg'
          : '0.06 0.13 0.24 rg',
        `1 0 0 1 ${cardX + 8} ${cardY + 22} Tm`,
        `(${sanitizePdfText(kpi.value)}) Tj`,
        'ET'
      );

      // KPI Label
      currentCommands.push(
        'BT',
        '/F1 8 Tf',
        '0.45 0.5 0.58 rg',
        `1 0 0 1 ${cardX + 8} ${cardY + 8} Tm`,
        `(${sanitizePdfText(kpi.label)}) Tj`,
        'ET'
      );
    });

    curY -= cardHeight + 20;
  }

  // Render Table Sections
  sections.forEach((sec) => {
    // Section Header
    if (sec.title) {
      if (curY < 120) startNewPage();
      currentCommands.push(
        'BT',
        '/F2 11 Tf',
        '0.06 0.13 0.24 rg',
        `1 0 0 1 ${margin} ${curY} Tm`,
        `(${sanitizePdfText(sec.title)}) Tj`,
        'ET'
      );
      curY -= 14;
    }

    if (sec.columns && sec.columns.length > 0) {
      const totalRelWidth = (sec.columnWidths || sec.columns.map(() => 1)).reduce((a, b) => a + b, 0);
      const computedColWidths = (sec.columnWidths || sec.columns.map(() => 1)).map(
        (w) => (w / totalRelWidth) * contentWidth
      );

      // Render Table Header
      if (curY < 100) startNewPage();
      const headerHeight = 20;
      currentCommands.push(
        'q',
        '0.12 0.18 0.28 rg', // Dark Slate Header
        `${margin} ${curY - headerHeight} ${contentWidth} ${headerHeight} re`,
        'f',
        'Q'
      );

      let colX = margin;
      sec.columns.forEach((col, cIdx) => {
        const colW = computedColWidths[cIdx];
        currentCommands.push(
          'BT',
          '/F2 8 Tf',
          '1 1 1 rg', // White
          `1 0 0 1 ${colX + 6} ${curY - 14} Tm`,
          `(${sanitizePdfText(col.toUpperCase())}) Tj`,
          'ET'
        );
        colX += colW;
      });
      curY -= headerHeight;

      // Render Rows
      sec.rows.forEach((row, rIdx) => {
        const rowHeight = 18;
        if (curY - rowHeight < 45) {
          startNewPage();
          // Repeat Table Header on new page
          currentCommands.push(
            'q',
            '0.12 0.18 0.28 rg',
            `${margin} ${curY - headerHeight} ${contentWidth} ${headerHeight} re`,
            'f',
            'Q'
          );
          let hX = margin;
          sec.columns.forEach((col, cIdx) => {
            const colW = computedColWidths[cIdx];
            currentCommands.push(
              'BT',
              '/F2 8 Tf',
              '1 1 1 rg',
              `1 0 0 1 ${hX + 6} ${curY - 14} Tm`,
              `(${sanitizePdfText(col.toUpperCase())}) Tj`,
              'ET'
            );
            hX += colW;
          });
          curY -= headerHeight;
        }

        // Zebra background fill
        if (rIdx % 2 === 1) {
          currentCommands.push(
            'q',
            '0.97 0.98 0.99 rg',
            `${margin} ${curY - rowHeight} ${contentWidth} ${rowHeight} re`,
            'f',
            'Q'
          );
        }

        // Row border bottom
        currentCommands.push(
          'q',
          '0.9 0.92 0.95 RG',
          '0.5 w',
          `${margin} ${curY - rowHeight} m ${margin + contentWidth} ${curY - rowHeight} l S`,
          'Q'
        );

        let cX = margin;
        row.forEach((cell, cIdx) => {
          const colW = computedColWidths[cIdx] || 60;
          currentCommands.push(
            'BT',
            '/F1 8 Tf',
            '0.15 0.2 0.28 rg',
            `1 0 0 1 ${cX + 6} ${curY - 13} Tm`,
            `(${sanitizePdfText(String(cell)).slice(0, Math.floor(colW / 5.5))}) Tj`,
            'ET'
          );
          cX += colW;
        });

        curY -= rowHeight;
      });

      curY -= 15;
    }
  });

  // Notes section
  if (notes.length > 0) {
    if (curY < 70) startNewPage();
    currentCommands.push(
      'BT',
      '/F2 9 Tf',
      '0.3 0.35 0.45 rg',
      `1 0 0 1 ${margin} ${curY} Tm`,
      '(Operational Notes & Governance:) Tj',
      'ET'
    );
    curY -= 12;

    notes.forEach((note) => {
      if (curY < 45) startNewPage();
      currentCommands.push(
        'BT',
        '/F1 8 Tf',
        '0.4 0.45 0.55 rg',
        `1 0 0 1 ${margin + 8} ${curY} Tm`,
        `(* ${sanitizePdfText(note)}) Tj`,
        'ET'
      );
      curY -= 11;
    });
  }

  // Push final page
  if (currentCommands.length > 0) {
    pages.push(currentCommands.join('\n'));
  }

  // Footers with page numbers
  const totalPages = pages.length;
  pages.forEach((_, pIdx) => {
    pages[pIdx] += `\nq 0.85 0.88 0.92 RG 0.5 w ${margin} 30 m ${margin + contentWidth} 30 l S Q\nBT /F1 7 Tf 0.55 0.6 0.68 rg 1 0 0 1 ${margin} 20 Tm (Customer Support System Confidential  |  ${sanitizePdfText(title)}) Tj 1 0 0 1 ${pageWidth - margin - 60} 20 Tm (Page ${pIdx + 1} of ${totalPages}) Tj ET`;
  });

  // Assemble PDF Objects
  const pdfObjects: string[] = [];
  pdfObjects.push('<< /Type /Catalog /Pages 2 0 R >>'); // 1 0 obj: Catalog

  // 2 0 obj: Pages
  const pageObjIds = pages.map((_, i) => `${3 + i * 2} 0 R`).join(' ');
  pdfObjects.push(`<< /Type /Pages /Kids [${pageObjIds}] /Count ${totalPages} >>`);

  // Fonts
  const f1Id = 3 + totalPages * 2;
  const f2Id = f1Id + 1;

  pages.forEach((contentStream, pIdx) => {
    const pageId = 3 + pIdx * 2;
    const streamId = pageId + 1;

    // Page Object
    pdfObjects.push(
      `<< /Type /Page /Parent 2 0 R /MediaBox [0 0 ${pageWidth} ${pageHeight}] /Resources << /Font << /F1 ${f1Id} 0 R /F2 ${f2Id} 0 R >> >> /Contents ${streamId} 0 R >>`
    );

    // Stream Object
    const streamBytes = contentStream;
    pdfObjects.push(`<< /Length ${streamBytes.length} >>\nstream\n${streamBytes}\nendstream`);
  });

  // Font Objects
  pdfObjects.push('<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>');
  pdfObjects.push('<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>');

  // Build Binary Output & Cross Reference Table
  let output = '%PDF-1.4\n';
  const offsets: number[] = [0];

  pdfObjects.forEach((obj, idx) => {
    offsets.push(output.length);
    output += `${idx + 1} 0 obj\n${obj}\nendobj\n`;
  });

  const xrefOffset = output.length;
  output += `xref\n0 ${pdfObjects.length + 1}\n0000000000 65535 f \n`;
  for (let i = 1; i <= pdfObjects.length; i++) {
    output += `${String(offsets[i]).padStart(10, '0')} 00000 n \n`;
  }
  output += `trailer\n<< /Size ${pdfObjects.length + 1} /Root 1 0 R >>\nstartxref\n${xrefOffset}\n%%EOF`;

  // Download Blob
  const blob = new Blob([output], { type: 'application/pdf' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = fileName.endsWith('.pdf') ? fileName : `${fileName}.pdf`;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

